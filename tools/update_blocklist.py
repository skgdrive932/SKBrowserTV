#!/usr/bin/env python3
"""Merge a large public ad/tracker host list into the app's blocklist.

Run on your PC from the repository root:   python3 tools/update_blocklist.py
Then rebuild the app. The existing entries in blocklist.txt are kept.
"""
import urllib.request

SRC = "https://raw.githubusercontent.com/StevenBlack/hosts/master/hosts"
OUT = "app/src/main/assets/blocklist.txt"

domains = set()

# keep what is already in the file
try:
    with open(OUT, encoding="utf-8") as f:
        for line in f:
            line = line.split("#")[0].strip().lower()
            if line:
                domains.add(line.split()[-1])
except FileNotFoundError:
    pass

data = urllib.request.urlopen(SRC, timeout=60).read().decode("utf-8", "ignore")
for line in data.splitlines():
    line = line.split("#")[0].strip().lower()
    parts = line.split()
    if len(parts) >= 2 and parts[0] in ("0.0.0.0", "127.0.0.1"):
        d = parts[1]
        if d not in ("localhost", "0.0.0.0", "broadcasthost") and "." in d:
            domains.add(d)

with open(OUT, "w", encoding="utf-8") as f:
    f.write("# SK Browser TV blocklist (generated by tools/update_blocklist.py)\n")
    f.write("\n".join(sorted(domains)) + "\n")

print(f"Wrote {len(domains)} domains to {OUT}")
